describe('형식 판별', () => {
  it('내용으로 npm / pnpm / Yarn 을 구분하고, 모르면 파일 이름을 참고한다', () => {
    expect(detectLockfileFormat('{"lockfileVersion":3}')).toBe('NPM');
    expect(detectLockfileFormat(PNPM_V9)).toBe('PNPM');
    expect(detectLockfileFormat('# THIS IS AN AUTOGENERATED FILE.\n# yarn lockfile v1\n\n')).toBe('YARN');
    expect(detectLockfileFormat('# comment\n\n__metadata:\n  version: 8\n')).toBe('YARN');
    expect(detectLockfileFormat('anything', 'sub/dir/pnpm-lock.yaml')).toBe('PNPM');
    expect(detectLockfileFormat('anything', 'readme.md')).toBeNull();
  });
});

describe('pnpm-lock.yaml', () => {
  const parsed = parseLockfile(PNPM_V9, limits);

  it('앞쪽 환경 정보 문서가 아니라 실제 lockfile 문서를 읽는다', () => {
    expect(parsed.format).toBe('PNPM');
    expect(parsed.lockfileVersion).toBe(9);
    expect(find(parsed, 'pnpm')).toBeUndefined();
  });

  it('워크스페이스 importer 의 의존성을 직접 의존성으로 보고 경로를 남긴다', () => {
    const core = find(parsed, '@nestjs/core', '12.6.0');
    expect(core).toMatchObject({ isDirect: true, isDev: false, refKind: 'REGISTRY', scannable: true, dependencyPath: ['@nestjs/core@12.6.0'] });
    const ptr = find(parsed, 'path-to-regexp', '8.4.2');
    expect(ptr).toMatchObject({ isDirect: false, isDev: false });
    expect(ptr?.dependencyPath).toEqual(['@nestjs/core@12.6.0', 'path-to-regexp@8.4.2']);
    // 다른 워크스페이스의 직접 의존성
    expect(find(parsed, 'reflect-metadata')?.isDirect).toBe(true);
  });

  it('peer 조합 표기는 버전에서 떼어 내고, 같은 버전은 하나로 합친다', () => {
    expect(parsed.packages.filter((p) => p.name === '@nestjs/core')).toHaveLength(1);
  });

  it('개발 의존성으로만 도달하는 패키지를 개발 의존성으로 표시한다', () => {
    expect(find(parsed, 'vitest')).toMatchObject({ isDirect: true, isDev: true });
    expect(find(parsed, 'debug')).toMatchObject({ isDirect: false, isDev: true });
    // 운영 경로로도 도달하면 개발 의존성이 아니다
    expect(find(parsed, 'path-to-regexp')?.isDev).toBe(false);
  });

  it('선택 의존성, 별칭, git, 워크스페이스 링크를 구분한다', () => {
    expect(find(parsed, 'fsevents')?.isOptional).toBe(true);
    expect(find(parsed, 'string-width', '4.2.3')).toMatchObject({ refKind: 'ALIAS', scannable: true, isDirect: true });
    expect(find(parsed, 'gitdep')).toMatchObject({ refKind: 'REMOTE_TARBALL', scannable: false });
    expect(find(parsed, '@acme/shared')).toBeUndefined();
    expect(parsed.warnings.find((w) => w.code === 'LOCAL_PACKAGE')?.examples).toContain('@acme/shared');
  });

  it('lockfileVersion 6 형식(/name@version 키)을 읽는다', () => {
    const v6 = `lockfileVersion: '6.0'

dependencies:
  express:
    specifier: ^4.18.0
    version: 4.18.2

devDependencies:
  ms:
    specifier: 2.1.2
    version: 2.1.2

packages:

  /express@4.18.2:
    resolution: {integrity: sha512-a}
    dependencies:
      ms: 2.0.0
    dev: false

  /ms@2.0.0:
    resolution: {integrity: sha512-b}
    dev: false

  /ms@2.1.2:
    resolution: {integrity: sha512-c}
    dev: true
`;
    const result = parseLockfile(v6, limits);
    expect(result.lockfileVersion).toBe(6);
    expect(find(result, 'express')).toMatchObject({ version: '4.18.2', isDirect: true, isDev: false });
    expect(find(result, 'ms', '2.0.0')).toMatchObject({ isDirect: false, isDev: false, dependencyPath: ['express@4.18.2', 'ms@2.0.0'] });
    expect(find(result, 'ms', '2.1.2')).toMatchObject({ isDirect: true, isDev: true });
  });

  it('lockfileVersion 5 형식(/name/version_peer 키)을 읽는다', () => {
    const v5 = `lockfileVersion: 5.4

specifiers:
  react-dom: ^17.0.0
  '@babel/core': ^7.0.0

dependencies:
  react-dom: 17.0.2_react@17.0.2
  '@babel/core': 7.12.3

packages:

  /react-dom/17.0.2_react@17.0.2:
    resolution: {integrity: sha512-a}
    dependencies:
      react: 17.0.2
    dev: false

  /react/17.0.2:
    resolution: {integrity: sha512-b}
    dev: false

  /@babel/core/7.12.3:
    resolution: {integrity: sha512-c}
    dev: false
`;
    const result = parseLockfile(v5, limits);
    expect(result.lockfileVersion).toBe(5);
    expect(find(result, 'react-dom')).toMatchObject({ version: '17.0.2', isDirect: true });
    expect(find(result, 'react')).toMatchObject({ version: '17.0.2', isDirect: false, dependencyPath: ['react-dom@17.0.2', 'react@17.0.2'] });
    expect(find(result, '@babel/core')).toMatchObject({ version: '7.12.3', isDirect: true });
  });

  it('지원하지 않는 버전과 lockfile 이 아닌 YAML 을 거부한다', () => {
    expect(code(() => parseLockfile("lockfileVersion: '4.0'\nimporters: {}\n", limits))).toBe('UNSUPPORTED_VERSION');
    expect(code(() => parseLockfile('lockfileVersion: 9\n', limits))).toBe('NOT_A_LOCKFILE');
    expect(code(() => parseLockfile('lockfileVersion: [', limits, null, 'pnpm-lock.yaml'))).toBe('INVALID_FORMAT');
  });

  const real = '../../pnpm-lock.yaml';
  it.skipIf(!existsSync(real))('이 저장소의 실제 pnpm-lock.yaml 을 빠르게 해석한다', () => {
    const start = performance.now();
    const result = parseLockfile(readFileSync(real, 'utf8'), { maxBytes: 20 * 1024 * 1024, maxPackages: 50_000 });
    expect(performance.now() - start).toBeLessThan(3000);
    expect(result.format).toBe('PNPM');
    expect(result.packages.length).toBeGreaterThan(300);
    expect(find(result, '@nestjs/core')?.isDirect).toBe(true);
    expect(find(result, 'vite')?.isDev).toBe(true);
    expect(result.packages.every((p) => p.dependencyPath.length > 0)).toBe(true);
  });
});

