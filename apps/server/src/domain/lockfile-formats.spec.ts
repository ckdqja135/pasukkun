import { existsSync, readFileSync } from 'node:fs';
import { LockfileError, detectLockfileFormat, parseLockfile, type ParsedLockfile } from './lockfile.js';

const limits = { maxBytes: 2 * 1024 * 1024, maxPackages: 1000 };
const code = (fn: () => unknown) => {
  try {
    fn();
  } catch (error) {
    return error instanceof LockfileError ? error.code : `OTHER:${String(error)}`;
  }
  return 'NO_ERROR';
};
const find = (parsed: ParsedLockfile, name: string, version?: string) =>
  parsed.packages.find((p) => p.name === name && (version === undefined || p.version === version));

