describe('YAML lockfile - 서비스 거부·오염을 노린 입력', () => {
  it('별칭(앵커) 폭증 입력을 해석하지 않는다', () => {
    const bomb = [
      "lockfileVersion: '9.0'",
      'a: &a ["x","x","x","x","x","x","x","x","x"]',
      'b: &b [*a,*a,*a,*a,*a,*a,*a,*a,*a]',
      'c: &c [*b,*b,*b,*b,*b,*b,*b,*b,*b]',
      'd: &d [*c,*c,*c,*c,*c,*c,*c,*c,*c]',
      'e: [*d,*d,*d,*d,*d,*d,*d,*d,*d]',
    ].join('\n');
    expect(code(() => parseLockfile(bomb, limits))).toBe('INVALID_FORMAT');
  });

  it('지나친 중첩과 중복 키를 거부한다', () => {
    const deep = `lockfileVersion: '9.0'\nx: ${'['.repeat(50_000)}${']'.repeat(50_000)}\n`;
    expect(code(() => parseLockfile(deep, limits))).toBe('INVALID_FORMAT');
    expect(code(() => parseLockfile("lockfileVersion: '9.0'\nimporters: {}\nimporters: {}\n", limits))).toBe('INVALID_FORMAT');
  });

  it('__proto__ 키로 프로토타입을 오염시킬 수 없다', () => {
    const lock = `lockfileVersion: '9.0'\nimporters:\n  __proto__:\n    dependencies:\n      polluted: {specifier: 1.0.0, version: 1.0.0}\n`;
    parseLockfile(lock, limits);
    expect(({} as Record<string, unknown>).dependencies).toBeUndefined();
  });

  it('패키지 수 제한과 크기 제한을 적용한다', () => {
    const many = Array.from({ length: 1100 }, (_, i) => `  p${i}@1.0.0: {}`).join('\n');
    expect(code(() => parseLockfile(`lockfileVersion: '9.0'\nimporters:\n  .: {}\nsnapshots:\n${many}\n`, limits))).toBe('TOO_MANY_PACKAGES');
    const entries = Array.from({ length: 1100 }, (_, i) => `p${i}@^1.0.0:\n  version "1.0.0"\n`).join('\n');
    expect(code(() => parseLockfile(`# yarn lockfile v1\n\n${entries}`, limits))).toBe('TOO_MANY_PACKAGES');
    expect(code(() => parseLockfile(`# yarn lockfile v1\n${'#'.repeat(3 * 1024 * 1024)}`, limits))).toBe('TOO_LARGE');
  });

  it('실제 크기의 pnpm lockfile 도 빠르게 처리한다', () => {
    const n = 5000;
    const snapshots = Array.from({ length: n }, (_, i) => {
      const deps = Array.from({ length: 6 }, (_, d) => `      pkg-${(i * 7 + d * 13 + 1) % n}: 1.0.0`).join('\n');
      return `  pkg-${i}@1.0.0:\n    dependencies:\n${deps}`;
    }).join('\n');
    const packages = Array.from({ length: n }, (_, i) => `  pkg-${i}@1.0.0:\n    resolution: {integrity: sha512-x}`).join('\n');
    const lock = `lockfileVersion: '9.0'\nimporters:\n  .:\n    dependencies:\n      pkg-0: {specifier: 1.0.0, version: 1.0.0}\npackages:\n${packages}\nsnapshots:\n${snapshots}\n`;
    const start = performance.now();
    const result = parseLockfile(lock, { maxBytes: 20 * 1024 * 1024, maxPackages: 50_000 });
    expect(result.packages).toHaveLength(n);
    expect(performance.now() - start).toBeLessThan(5000);
  });
});
