describe('yarn.lock (Yarn 1)', () => {
  const parsed = parseLockfile(YARN_V1, limits, YARN_PKG);

  it('설치 버전과 레지스트리 출처를 읽는다 (# 해시가 붙은 resolved 포함)', () => {
    expect(parsed).toMatchObject({ format: 'YARN', lockfileVersion: 1, rootName: 'web' });
    expect(find(parsed, '@babel/code-frame')).toMatchObject({ version: '7.12.13', refKind: 'REGISTRY', scannable: true, isDirect: true });
    expect(parsed.packages.filter((p) => p.name === 'lodash')).toHaveLength(1);
  });

  it('package.json 으로 직접·개발 의존성을 구분하고 경로를 남긴다', () => {
    expect(find(parsed, '@babel/highlight')).toMatchObject({ isDirect: false, dependencyPath: ['@babel/code-frame@7.12.13', '@babel/highlight@7.13.10'] });
    expect(find(parsed, 'jest')).toMatchObject({ isDirect: true, isDev: true });
    expect(find(parsed, 'fsevents')).toMatchObject({ isDirect: false, isDev: true });
    expect(find(parsed, 'lodash')?.isDev).toBe(false);
  });

  it('별칭과 git 참조를 구분한다', () => {
    expect(find(parsed, 'string-width')).toMatchObject({ refKind: 'ALIAS', scannable: true });
    expect(find(parsed, 'gitdep')).toMatchObject({ refKind: 'GIT', scannable: false });
  });

  it('package.json 이 없으면 모두 검사하되 직접 의존성을 알 수 없다고 알린다', () => {
    const bare = parseLockfile(YARN_V1, limits);
    expect(bare.packages.every((p) => !p.isDirect)).toBe(true);
    expect(bare.packages.filter((p) => p.scannable)).toHaveLength(parsed.packages.filter((p) => p.scannable).length);
    expect(bare.warnings.some((w) => w.code === 'DIRECT_UNKNOWN')).toBe(true);
  });

  it('형식이 깨진 파일을 거부한다', () => {
    expect(code(() => parseLockfile('# yarn lockfile v1\n\nnot an entry line\n', limits))).toBe('INVALID_FORMAT');
  });
});

